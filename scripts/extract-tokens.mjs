// Generates packages/tokens/src/{tokens,fonts,base}.css from the entry stylesheets of the cached build.
//   tokens.css  every custom-property rule from the design-token stylesheet (themes, high contrast, density…)
//   fonts.css   @font-face rules for the UI font families, with the woff2 files copied next to it
//   base.css    the global reset stylesheet (body, html, form defaults) plus every custom-property-only
//               global rule (:root, .theme-*) from the remaining entry stylesheets
import fs from 'node:fs';
import path from 'node:path';
import postcss from 'postcss';
import * as prettier from 'prettier';

const CACHE = path.resolve('.cache');
const ASSETS = path.join(CACHE, 'assets');
const OUT = path.resolve('packages/tokens/src');
const ORIGIN = process.env.DISCORD_ORIGIN ?? 'https://canary.discord.com';
const FONT_FAMILIES =
  /^(gg sans|gg mono|ABC Ginto Nord|ABC Ginto Discord Nord|ABC Ginto Discord|Noto Sans|Source Code Pro)$/;
const HASHED_CLASS = /\.-?[A-Za-z_][\w-]*?_[\w-]{6}(?![\w-])|#[\w-]+_[\w-]{6}(?![\w-])/;

const html = fs.readFileSync(path.join(CACHE, 'app.html'), 'utf8');
const entryCss = [...html.matchAll(/href="\/assets\/([^"]+\.css)"/g)].map((m) => m[1]);
const read = (file) => fs.readFileSync(path.join(ASSETS, file), 'utf8');
const countVars = (css) => css.match(/;--[\w-]+:/g)?.length ?? 0;
const tokenFile = entryCss.reduce((best, f) => (countVars(read(f)) > countVars(read(best)) ? f : best));
const resetFile = entryCss.find((f) =>
  /\}body\{background:transparent;font-family:var\(--font-primary\)/.test(read(f)),
);
if (!resetFile) throw new Error('reset stylesheet not found');
if (!tokenFile) throw new Error('token stylesheet not found');

const format = (css) => prettier.format(css, { parser: 'css', printWidth: 120 });
const header = (what) => `/* Generated by scripts/extract-tokens.mjs from ${what}. Do not edit by hand. */\n`;
const build = html.match(/BUILD_NUMBER":"(\d+)"/)?.[1];

const tokens = postcss.parse(fs.readFileSync(path.join(ASSETS, tokenFile), 'utf8'));
const fonts = postcss.root();
fs.mkdirSync(path.join(OUT, 'fonts'), { recursive: true });
const downloads = [];
tokens.walkAtRules('font-face', (rule) => {
  let family = '';
  rule.walkDecls('font-family', (d) => (family = d.value.replace(/^["']|["']$/g, '')));
  if (FONT_FAMILIES.test(family)) {
    const copy = rule.clone();
    copy.walkDecls('src', (d) => {
      d.value = d.value.replace(/url\("?\/assets\/([^")]+)"?\)/g, (_, file) => {
        downloads.push(file);
        return `url("./fonts/${file}")`;
      });
    });
    fonts.append(copy);
  }
  rule.remove();
});
for (const file of downloads) {
  const dest = path.join(OUT, 'fonts', file);
  if (fs.existsSync(dest)) continue;
  const res = await fetch(`${ORIGIN}/assets/${file}`);
  if (!res.ok) throw new Error(`font ${file}: ${res.status}`);
  fs.writeFileSync(dest, Buffer.from(await res.arrayBuffer()));
}

const base = postcss.root();
for (const file of entryCss.filter((f) => f !== tokenFile)) {
  const root = postcss.parse(fs.readFileSync(path.join(ASSETS, file), 'utf8'));
  root.walk((node) => {
    if (node.parent?.type === 'atrule' && /keyframes$/.test(node.parent.name)) return;
    const isGlobal = node.type === 'rule' && !HASHED_CLASS.test(node.selector);
    const onlyVars = isGlobal && node.nodes.every((d) => d.type !== 'decl' || d.prop.startsWith('--'));
    const isGlobalRule = isGlobal && (file === resetFile || onlyVars);
    const isGlobalKeyframes =
      file === resetFile && node.type === 'atrule' && /keyframes$/.test(node.name) && !/_[\w-]{6}$/.test(node.params);
    if (!isGlobalRule && !isGlobalKeyframes) return;
    let wrapped = node.clone();
    for (let parent = node.parent; parent?.type === 'atrule'; parent = parent.parent) {
      wrapped = parent.clone({ nodes: [] }).append(wrapped);
    }
    base.append(wrapped);
  });
}

fs.writeFileSync(
  path.join(OUT, 'tokens.css'),
  header(`build ${build} ${tokenFile}`) + (await format(tokens.toString())),
);
fs.writeFileSync(path.join(OUT, 'fonts.css'), header(`build ${build} ${tokenFile}`) + (await format(fonts.toString())));
fs.writeFileSync(
  path.join(OUT, 'base.css'),
  header(`build ${build} entry stylesheets`) + (await format(base.toString())),
);
console.log(`tokens from ${tokenFile}, ${downloads.length} font files, base from ${entryCss.length - 1} stylesheets`);
