import fs from 'node:fs';
import path from 'node:path';
import react from '@vitejs/plugin-react';
import { defineConfig, type Plugin } from 'vite';

const PUBLIC_DIR = path.resolve(import.meta.dirname, 'public');
const VIDEO_RE = /\.(mp4|webm|mov)$/i;

/** The sample poster for a video under public/ (`<name>-poster.jpg|png`), as a URL path. */
const findPoster = (videoPath: string) => {
  const base = videoPath.replace(VIDEO_RE, '-poster');
  return ['.jpg', '.png'].map((ext) => base + ext).find((p) => fs.existsSync(path.join(PUBLIC_DIR, p)));
};

const listVideos = (dir: string): string[] =>
  fs.readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const file = path.join(dir, entry.name);
    if (entry.isDirectory()) return listVideos(file);
    return VIDEO_RE.test(entry.name) ? ['/' + path.relative(PUBLIC_DIR, file).split(path.sep).join('/')] : [];
  });

// A static host can't answer by query string, so builds emulate the proxy in the browser with a service worker
// (registered by src/mediaProxy.ts) that knows every sample video's poster.
const serviceWorker = (posters: Record<string, string>) => `// Generated by vite.config.ts.
const POSTERS = ${JSON.stringify(posters)};
self.addEventListener('install', () => self.skipWaiting());
self.addEventListener('activate', (event) => event.waitUntil(self.clients.claim()));
self.addEventListener('message', (event) => {
  if (event.data === 'claim') event.waitUntil(self.clients.claim());
});
self.addEventListener('fetch', (event) => {
  const url = new URL(event.request.url);
  if (url.origin !== self.location.origin || !url.searchParams.has('format')) return;
  const poster = POSTERS[url.pathname];
  if (poster != null) event.respondWith(fetch(poster));
});
`;

// Discord's media proxy serves a video's first frame when asked for an image format (`?format=webp`), which
// is how the client gets video posters from `proxy_url`. The sample media emulate it with `<name>-poster.*`.
const mediaProxyPosters = (): Plugin => ({
  name: 'media-proxy-posters',
  configureServer(server) {
    server.middlewares.use((req, _res, next) => {
      const url = new URL(req.url ?? '/', 'http://localhost');
      if (VIDEO_RE.test(url.pathname) && url.searchParams.has('format')) {
        const poster = findPoster(url.pathname);
        if (poster != null) req.url = poster;
      }
      next();
    });
  },
  generateBundle() {
    const posters = Object.fromEntries(
      listVideos(PUBLIC_DIR).flatMap((video) => {
        const poster = findPoster(video);
        return poster != null ? [[video, poster]] : [];
      }),
    );
    this.emitFile({ type: 'asset', fileName: 'media-proxy-sw.js', source: serviceWorker(posters) });
  },
});

export default defineConfig({
  plugins: [react(), mediaProxyPosters()],
});
